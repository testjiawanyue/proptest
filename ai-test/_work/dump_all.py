def dump(ids_by_sheet, path):
    out=io.open(path,"w",encoding="utf-8")
    for sheet, ids in ids_by_sheet:
        idx={c.get("用例编号"):c for c in data[sheet]}
        for cid in ids:
            c=idx.get(cid)
            if not c:
                out.write(f"\n### NOT FOUND {sheet}/{cid}\n"); continue
            out.write(f"\n{'='*80}\n{sheet}/{cid}  优先级:{c.get('优先级')}\n")
            for k in ["用例标题","测试点","前置条件","测试步骤","预期结果","备注"]:
                out.write(f"【{k}】{c.get(k,'')}\n")
    out.close()

